package com.project200.domain.model

/**
 * 세션을 정리하는 이유입니다. 정리 범위가 이유에 따라 다릅니다.
 *
 * 호출부는 무엇을 지울지 고르지 않고 무슨 일이 있었는지만 알립니다. 지울 범위는
 * `ClearSessionUseCase`가 정합니다
 */
enum class SessionExitReason {
    /** 사용자가 로그아웃이나 탈퇴를 눌렀습니다. 기기에 남은 데이터를 모두 지웁니다 */
    USER_INITIATED,

    /**
     * 토큰 만료나 갱신 실패처럼 사용자가 의도하지 않은 이탈입니다.
     *
     * 아직 서버에 올리지 못한 전송 대기 행을 지키기 위해 캐시와 회원ID를 남기고 토큰만
     * 지웁니다. 회원ID를 남기는 이유는 재로그인 때 계정 전환 판정에 쓰이기 때문입니다.
     * 회원ID가 없으면 같은 계정으로 돌아와도 이전 값과 다르다고 보고 캐시를 지웁니다
     */
    FORCED,
}
